export const isCategoryNameReserved = (name) => {
  if (!name || typeof name !== 'string') return false;
  const clean = name.trim().toLowerCase();
  return RESERVED_CATEGORY_NAMES.some((reserved) => reserved.toLowerCase() === clean);
};

